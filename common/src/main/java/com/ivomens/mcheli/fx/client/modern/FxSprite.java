package com.ivomens.mcheli.fx.client.modern;

import com.ivomens.mcheli.util.Ids;
import com.mojang.blaze3d.platform.GlStateManager;
import com.mojang.blaze3d.systems.RenderSystem;
import com.mojang.blaze3d.vertex.BufferBuilder;
import com.mojang.blaze3d.vertex.DefaultVertexFormat;
import com.mojang.blaze3d.vertex.Tesselator;
import com.mojang.blaze3d.vertex.VertexFormat;
import net.minecraft.client.particle.ParticleRenderType;
import net.minecraft.client.renderer.GameRenderer;
import net.minecraft.client.renderer.texture.AbstractTexture;
import net.minecraft.client.renderer.texture.TextureManager;
import net.minecraft.resources.ResourceLocation;

/**
 * The sprite sheets used by the modern particles. Each sheet is eight 64 px frames in a row,
 * played left to right over the particle's life. The textures are generated by
 * {@code tools/generate_fx_textures.py}.
 */
public enum FxSprite {
    SMOKE("smoke", Blend.TRANSLUCENT),
    DUST("dust", Blend.TRANSLUCENT),
    FLAME("flame", Blend.ADDITIVE),
    SPARK("spark", Blend.ADDITIVE),
    DEBRIS("debris", Blend.OPAQUE_CUTOUT),
    SHOCKWAVE("shockwave", Blend.ADDITIVE),
    FLASH("flash", Blend.ADDITIVE);

    public static final int FRAMES = 8;

    enum Blend { TRANSLUCENT, ADDITIVE, OPAQUE_CUTOUT }

    final ResourceLocation texture;
    final Blend blend;
    final ParticleRenderType renderType;

    FxSprite(String name, Blend blend) {
        this.texture = Ids.of("textures/fx/" + name + ".png");
        this.blend = blend;
        this.renderType = createRenderType(this);
    }

    /** Glowing sprites ignore world light. */
    boolean isEmissive() {
        return blend == Blend.ADDITIVE;
    }

    private static ParticleRenderType createRenderType(FxSprite sprite) {
        return new ParticleRenderType() {
            private boolean filterSet;

            @Override
            public BufferBuilder begin(Tesselator tesselator, TextureManager textures) {
                if (!filterSet) {
                    // the sheets are soft gradients, so sample them smoothly instead of pixelated
                    AbstractTexture texture = textures.getTexture(sprite.texture);
                    texture.setFilter(true, false);
                    filterSet = true;
                }
                RenderSystem.setShader(GameRenderer::getParticleShader);
                RenderSystem.setShaderTexture(0, sprite.texture);
                RenderSystem.enableBlend();
                switch (sprite.blend) {
                    case ADDITIVE -> {
                        RenderSystem.blendFunc(GlStateManager.SourceFactor.SRC_ALPHA, GlStateManager.DestFactor.ONE);
                        RenderSystem.depthMask(false);
                    }
                    case TRANSLUCENT -> {
                        RenderSystem.defaultBlendFunc();
                        RenderSystem.depthMask(false);
                    }
                    case OPAQUE_CUTOUT -> {
                        RenderSystem.defaultBlendFunc();
                        RenderSystem.depthMask(true);
                    }
                }
                return tesselator.begin(VertexFormat.Mode.QUADS, DefaultVertexFormat.PARTICLE);
            }

            // NeoForge hook, without @Override since plain vanilla has no such method:
            // opaque sprites draw before translucent blocks.
            public boolean isTranslucent() {
                return sprite.blend != Blend.OPAQUE_CUTOUT;
            }

            @Override
            public String toString() {
                return "MCHELI_FX_" + sprite.name();
            }
        };
    }
}
